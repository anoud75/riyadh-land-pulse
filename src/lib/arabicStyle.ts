const HINDI = "٠١٢٣٤٥٦٧٨٩";

/** Mechanical, meaning-preserving fixes only (digits, spacing, a few fixed phrases). */
export function polishArabic(text: string): string {
  return text
    .replace(/[٠-٩]/g, (d) => String(HINDI.indexOf(d)))
    .replace(/[ \t]+([،,.:؛!?؟])/g, "$1")
    .replace(/[ \t]{2,}/g, " ")
    .replace(/بالتالي/g, "لذا")
    .replace(/يتواجد/g, "يوجد")
    .replace(/تتواجد/g, "توجد")
    .replace(/ملفت/g, "لافت")
    .replace(/ما يزال/g, "ما زال")
    .replace(/لا زال/g, "ما زال")
    .replace(/حوالي/g, "نحو");
}
